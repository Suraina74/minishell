#include "libft.h"

int	ft_isalnum(int an)
{
	if ((an >= '0' && an <= '9') || (an >= 'a' && an <= 'z') || \
(an >= 'A' && an <= 'Z') || an == '_')
		return (0);
	else
		return (1);
}
